import { chromium } from 'playwright';
import fs from 'node:fs/promises';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
await fs.mkdir('tmp/loader-preview',{recursive:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
await page.goto('http://127.0.0.1:5173/?intro=replay');
await page.waitForTimeout(1700);await page.screenshot({path:'tmp/loader-preview/growing.png'});
await page.waitForTimeout(1100);await page.screenshot({path:'tmp/loader-preview/bloomed.png'});
await page.waitForTimeout(900);await page.screenshot({path:'tmp/loader-preview/dissolve.png'});
await page.locator('.blossom-loader').waitFor({state:'detached',timeout:20000});
console.log('desktop',await page.evaluate(()=>({overflow:document.body.style.overflow,inert:document.querySelector('#smooth-wrapper').inert,seen:sessionStorage.getItem('portfolio-blossom-seen')})));
await page.goto('http://127.0.0.1:5173/');
console.log('repeat visit loader count',await page.locator('.blossom-loader').count());
await page.setViewportSize({width:390,height:844});await page.goto('http://127.0.0.1:5173/?intro=replay');
await page.waitForTimeout(2800);await page.screenshot({path:'tmp/loader-preview/mobile.png'});
await page.locator('.blossom-loader').waitFor({state:'detached',timeout:20000});
await page.emulateMedia({reducedMotion:'reduce'});await page.goto('http://127.0.0.1:5173/?intro=replay');
await page.locator('.blossom-loader').waitFor({state:'detached',timeout:10000});
console.log('reduced motion completed');
console.log('errors',errors);await browser.close();
if(errors.length)process.exitCode=1;
