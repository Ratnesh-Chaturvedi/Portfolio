import { chromium } from 'playwright';
import fs from 'node:fs/promises';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
const assetRequests=[];page.on('request',r=>{if(r.url().includes('/loader/'))assetRequests.push(r.url());});
await fs.mkdir('tmp/loader-preview',{recursive:true});
await page.goto('http://127.0.0.1:5173/?intro=replay');
await page.waitForFunction(()=>document.querySelector('.blossom-loader')?.dataset.phase==='growing');
await page.waitForTimeout(900);await page.screenshot({path:'tmp/loader-preview/3d-growing.png'});
await page.waitForFunction(()=>document.querySelector('.blossom-loader')?.dataset.phase==='falling');
await page.screenshot({path:'tmp/loader-preview/3d-bloomed.png'});
await page.waitForTimeout(1300);await page.screenshot({path:'tmp/loader-preview/3d-falling.png'});
await page.locator('.blossom-loader').waitFor({state:'detached',timeout:25000});
console.log('desktop ready',await page.evaluate(()=>({overflow:document.body.style.overflow,inert:document.querySelector('#smooth-wrapper').inert})));
await page.setViewportSize({width:390,height:844});await page.goto('http://127.0.0.1:5173/?intro=replay');
await page.waitForFunction(()=>document.querySelector('.blossom-loader')?.dataset.phase==='falling');
await page.screenshot({path:'tmp/loader-preview/3d-mobile.png'});
await page.locator('.blossom-loader').waitFor({state:'detached',timeout:25000});
console.log('mobile ready');
await page.emulateMedia({reducedMotion:'reduce'});await page.goto('http://127.0.0.1:5173/?intro=replay');
await page.locator('.blossom-loader').waitFor({state:'detached',timeout:10000});console.log('reduced motion ready');
console.log('image texture requests',assetRequests);console.log('errors',errors);
await browser.close();if(errors.length || assetRequests.some(url=>!url.includes('/materials/')))process.exitCode=1;
